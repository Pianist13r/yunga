# ЗАГОТОВКА ХУКА: «три вопроса перед ответом» (вариант для PowerShell 5.1, Windows)
# Объяснение идеи — etalons/hooks.md, хук 1.
#
# ЧТО ДЕЛАЕТ: ничего не проверяет и ничего не блокирует. Просто печатает
# твои три вопроса в нужный момент. Claude видит этот текст как слова от
# ТЕБЯ (через настройки), а не как свою мысль.
#
# КУДА ПОДКЛЮЧАТЬ: в настройки, в раздел хуков, на событие
#   [впиши событие — какое именно, скажут на уроке про хуки]
# Пример строки настроек (подставь своё событие и свой полный путь;
# обратные слэши в пути внутри настроек пишутся удвоенными):
#
#   "hooks": {
#     "[впиши событие]": [
#       { "hooks": [ { "type": "command",
#                      "command": "powershell -NoProfile -ExecutionPolicy Bypass -File \"[впиши полный путь к этому файлу]\"" } ] }
#     ]
#   }
#
# ПЕРЕД УСТАНОВКОЙ: копия файла настроек (протокол изменения).
# ПОСЛЕ УСТАНОВКИ: проверь, что хук реально срабатывает — сделай то
# действие, на которое он повешен, и убедись, что текст появился.
# Не появился — считай, что хука нет.
#
# ЕСЛИ В ВЫВОДЕ КРАКОЗЯБРЫ вместо русских букв — дело в кодировке файла:
# пересохрани его в UTF-8 и проверь ещё раз. Английский текст этой проблемы
# не даёт — это запасной вариант, если с кодировкой не вышло.

$tekst = @'
Напоминание от меня (владельца этого компьютера), проверь себя перед ответом:

1. [впиши свой первый вопрос — например: факт о файле/папке/сайте я проверил
   сейчас или вспоминаю по памяти?]
2. [впиши второй — например: не выдаю ли я прикидку «на глаз» за проверенный факт?]
3. [впиши третий — например: досмотрел ли я вывод команды до конца, а не по
   обрезанному куску?]

Хоть один ответ неудобный — сначала проверь, потом отвечай.
'@

Write-Output $tekst

# Ноль на выходе = «всё в порядке, продолжай». Этот хук ничего не запрещает.
exit 0
